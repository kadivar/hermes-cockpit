def test_the_events_are_the_ones_the_kernel_sends(gen):
    rows = gen.notify_events()
    names = {name for row in rows for name in (row["names"] or [row["event"]])}
    # each of these is a real send in the kernel today; a new send appears on the page by itself
    assert {
        "standup",
        "advisory",
        "ready_for_review",
        "updated_after_review",
        "tracker_comment",
        "pr_comments",
        "rereview",
        "pr_stale",
        "pr_stale_review",
        "ticket_done",
        "ci_failed",
        "ci_green",
    } <= names
    assert all(row["site"] and (row["key"] or row["event"] == "standup") for row in rows)
    standup = next(row for row in rows if row["event"] == "standup")
    assert standup["once"] is False and all(row["once"] for row in rows if row is not standup)
    page = gen.events_md()
    assert "COCKPIT_EVENT" in page and "COCKPIT_EVENT_KEY" in page
    for name in names:
        assert f"`{name}`" in page


def test_every_registered_doctor_check_is_on_the_doctor_page_with_its_lines_and_what_resolves_it(gen):
    from cockpitlib import doctor

    rows = gen.doctor_rows()
    assert [row["id"] for row in rows] == list(doctor.CHECKS)
    assert [row["id"] for row in rows if not row["messages"]] == []
    assert [row["id"] for row in rows if not row["fix"] and row["severity"] != "info"] == []
    page = gen.doctor_md()
    for row in rows:
        assert f"| `{row['id']}` |" in page
        assert row["fix"].replace("|", "\\|") in page
        for message in row["messages"]:
            assert message.replace("|", "\\|") in page


def test_the_doctor_page_sorts_each_check_under_its_tier_and_marks_the_pinned_security_checks(gen):
    import json

    from cockpitlib import doctor

    pinned = json.load(open(os.path.join(ROOT, "tests", "contract", "doctor-security.json"), encoding="utf-8"))[
        "security"
    ]
    page = gen.doctor_md()
    parts = {
        "error": page.split("\n## Errors\n", 1)[1].split("\n## Warnings\n", 1)[0],
        "warning": page.split("\n## Warnings\n", 1)[1].split("\n## Notes\n", 1)[0],
        "info": page.split("\n## Notes\n", 1)[1],
    }
    for check_id, spec in doctor.CHECKS.items():
        assert f"| `{check_id}` |" in parts[spec["severity"]], check_id
    marked = sorted(
        line.split("`")[1] for line in page.splitlines() if line.startswith("| `") and "| **security** |" in line
    )
    assert marked == sorted(pinned)
    assert "| `coding.command-missing` |" in parts["warning"]


def test_a_doctor_line_the_generator_cannot_read_stops_the_generation(gen, monkeypatch):
    from cockpitlib import doctor

    monkeypatch.setitem(doctor.CHECKS, "made-up.check", doctor._c("error", "nothing"))
    with pytest.raises(SystemExit) as stopped:
        gen.doctor_rows()
    assert "made-up.check" in str(stopped.value)


