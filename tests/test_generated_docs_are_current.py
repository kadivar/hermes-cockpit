"""The references under docs/reference and the editor schemas are written from the code by scripts/gen: the committed
files are what the code gives now, the same tree gives the same bytes twice, and no table is left with a hole."""

import importlib.machinery
import importlib.util
import os
import subprocess
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, "scripts", "gen")


@pytest.fixture(scope="module")
def gen():
    loader = importlib.machinery.SourceFileLoader("cockpit_scripts_gen", GEN)
    module = importlib.util.module_from_spec(importlib.util.spec_from_loader(loader.name, loader))
    loader.exec_module(module)
    return module


def test_the_committed_generated_files_are_what_the_code_gives_now():
    done = subprocess.run([sys.executable, GEN, "--check"], capture_output=True, text=True, check=False)
    assert done.returncode == 0, done.stdout + done.stderr


def test_the_same_tree_generates_the_same_bytes_twice(gen):
    assert gen.generated() == gen.generated()


def test_a_stale_or_missing_file_is_named(gen, tmp_path):
    gen.write(str(tmp_path))
    target = tmp_path / "docs" / "reference" / "cli.md"
    target.write_text(target.read_text(encoding="utf-8") + "edited by hand\n", encoding="utf-8")
    os.remove(tmp_path / "docs" / "reference" / "events.md")
    assert gen.stale(str(tmp_path)) == ["docs/reference/cli.md", "docs/reference/events.md"]
    assert gen.main(["--everything"]) == 2


def test_every_generated_page_says_it_is_generated_and_from_what(gen):
    for path, text in gen.generated().items():
        first = text.splitlines()[0] if path.endswith(".md") else text
        assert "Generated by scripts/gen from " in first, path


def test_every_pack_key_of_the_registry_is_on_the_reference_page(gen):
    from cockpitlib import pack_keys

    page = gen.pack_keys_md()
    for entry in pack_keys.ENTRIES:
        assert f"| `{entry['path']}` | {entry['type']} |" in page, pack_keys.label(entry)
        assert entry["doc"].replace("|", "\\|") in page, pack_keys.label(entry)
    for file in pack_keys.FILES:
        assert f"## {file}\n" in page


def test_a_default_named_by_a_constant_is_shown_as_its_value(gen):
    from cockpitlib import pack_keys

    refs = [entry for entry in pack_keys.ENTRIES if isinstance(entry.get("default"), pack_keys.Ref)]
    assert refs
    page = gen.pack_keys_md()
    assert "Ref(" not in page
    for entry in refs:
        assert gen._default_cell(entry).startswith(
            gen._code(gen.json.dumps(pack_keys.default_of(entry), ensure_ascii=False))
        ), entry["path"]


def test_every_command_is_on_the_command_page_with_its_example_and_options(gen):
    from cockpitlib import cli

    page = gen.cli_md()
    for name in cli.COMMANDS:
        section = page.split(f"\n## {name}\n", 1)[1].split("\n## ", 1)[0]
        for flag in cli.FLAGS.get(name, ()):
            assert f"`{flag}`" in section, (name, flag)
        for line in cli.EXAMPLES.get(name, "").split(" | "):
            assert line in section, (name, line)
    assert "still accepted" not in page


