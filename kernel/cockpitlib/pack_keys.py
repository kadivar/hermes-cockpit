# When the default stands in for what the pack wrote (`when`), as the reader decides it.
# fmt: off
ABSENT = "absent"       # only a key the pack does not name: x.get(key, DEFAULT)
NONE = "none"           # a key not named, or named with no value: `is None`
BLANK = "blank"         # not named, no value, or an empty text
FALSY = "falsy"         # any falsy value ([], "", 0, None): x.get(key) or DEFAULT
NOT_LIST = "not-list"   # anything but a list with items
# fmt: on
NOT_TEXT = "not-text"  # anything but a text with a character in it
WHENS = (ABSENT, NONE, BLANK, FALSY, NOT_LIST, NOT_TEXT)
TRUTHY = "<truthy>"  # a case's test: the other key holds any value that counts as set


class Ref:
    """A constant of a kernel module, named and not copied: "module:NAME", divided by `per` when the reader does."""

    def __init__(self, target: str, per: int = 1, item: str = ""):
        self.target, self.per, self.item = target, per, item

    def __repr__(self) -> str:
        if self.item:
            return f"Ref({self.target!r}, item={self.item!r})"
        return f"Ref({self.target!r})" if self.per == 1 else f"Ref({self.target!r}, per={self.per})"

    def value(self):
        import importlib

        module, name = self.target.split(":")
        found = getattr(importlib.import_module(f"{__package__}.{module}"), name)
        if self.item:
            return found[self.item]  # one entry of a constant that is a mapping
        return found / self.per if self.per != 1 else found


class Key:
    """Another key of the pack whose value is this key's default: a path in pack.yaml."""

    def __init__(self, path: str):
        self.path = path

    def __repr__(self) -> str:
        return f"Key({self.path!r})"


_MISSING = object()


def _k(path, kind, doc, example=_MISSING, *, file=PACK, default=_MISSING, **more) -> dict:
    entry = {"path": path, "file": file, "type": kind, "doc": doc}
    if example is not _MISSING:
        entry["example"] = example
    if default is not _MISSING:
        entry["default"] = default
        entry.setdefault("when", more.pop("when", ABSENT))
    entry.update(more)
    return entry


def _in(file, *entries) -> tuple:
    return tuple({**entry, "file": file} for entry in entries)


