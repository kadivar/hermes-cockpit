"""Every key a pack may set, as data: where it lives, its shape, its default and one sentence on what it does.

Nothing here checks a pack: pack.load and its validators do that, and this table only describes what they accept and
what the readers do with an absent value. A path is dotted; `*` stands for a name the pack chooses and `[]` for each
item of a list. A default is a literal, a Ref to the constant the reader itself uses (resolved on use, so this module
imports nothing), or a Key: the other pack key whose value stands in.
"""

