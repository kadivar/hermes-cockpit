ENTRIES = (*_TOP, *_REPOS, *_SKILLS, *_EGRESS, *_STAGING, *_HELPERS, *_ACCOUNTS, *_MIGRATE)
_BY_KEY = {(entry["file"], entry["path"]): entry for entry in ENTRIES}


def entries(file: str = "") -> tuple:
    """Every entry, or those of one file, in the order they are written here."""
    return tuple(entry for entry in ENTRIES if not file or entry["file"] == file)


def label(entry) -> str:
    """How a key is named outside its file: bare for pack.yaml, <file>:<path> for a companion file."""
    return entry["path"] if entry["file"] == PACK else f"{entry['file']}:{entry['path']}"


def split(name: str) -> tuple:
    """(file, path) of a key as label() writes it."""
    file, _, path = str(name).partition(":")
    return (file, path) if path and file in FILES else (PACK, str(name))


def segments(path: str) -> list:
    """A path's parts: names, `*` and `[]`, so a.b[].c is a, b, [], c; a list index reads as `[]`."""
    import re

    return ["[]" if part.startswith("[") else part for part in re.findall(r"\[\d*\]|[^.\[\]]+", str(path))]


def pattern_of(path: str) -> str:
    """The registry path a concrete one may stand for by its lists alone: repos[2].base is repos[].base."""
    import re

    return re.sub(r"\[\d+\]", "[]", str(path))


def find(name: str):
    """The entry a key names, or None: the path as written, a list index dropped, or a pack's own name under `*`."""
    file, path = split(name)
    path = pattern_of(path)
    if (file, path) in _BY_KEY:
        return _BY_KEY[(file, path)]
    want = segments(path)
    best = None
    for entry in ENTRIES:
        have = segments(entry["path"])
        if entry["file"] != file or len(have) != len(want) or "*" not in have:
            continue
        if all(mine in ("*", theirs) for mine, theirs in zip(have, want)):
            if best is None or have.count("*") < segments(best["path"]).count("*"):
                best = entry
    return best


def default_of(entry, lookup=None):
    """The value that stands in for an unset key: the literal, the reader's own constant, or the other key's value
    (lookup(path) answers that; without it a Key stays a Key). A case whose other key matches wins."""
    for path, test, value in (entry.get("cases") or ()) if lookup else ():
        other = lookup(path)
        if bool(other) if test == TRUTHY else (other == test and isinstance(other, bool) == isinstance(test, bool)):
            return value
    default = entry.get("default")
    if isinstance(default, Ref):
        value = default.value()
        return list(value) if isinstance(value, tuple) else value
    if isinstance(default, Key):
        return lookup(default.path) if lookup else default
    return default


def defaulted(entry, present: bool, value) -> bool:
    """True when the default stands in for what the pack wrote, by the entry's own `when`."""
    if "default" not in entry:
        return False
    when = entry.get("when", ABSENT)
    if not present:
        return True
    if when == ABSENT:
        return False
    if when == NONE:
        return value is None
    if when == BLANK:
        return value is None or value == ""
    if when == NOT_LIST:
        return not (isinstance(value, (list, tuple)) and value)
    if when == NOT_TEXT:
        return not (isinstance(value, str) and value.strip())
    return not value
